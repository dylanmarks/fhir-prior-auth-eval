import type { BenchmarkAggregateMetrics } from '../metrics/scoring.js';
import type { SensitivityReport } from '../mutations/sensitivity.js';

export interface ReportConfig {
  datasetVersion?: string;
  runMode?: 'offline_deterministic' | 'live_inference';
  strategyName?: string;
}

export class MarkdownReporter {
  public static generateReport(
    metrics: BenchmarkAggregateMetrics,
    sensitivity?: SensitivityReport,
    config?: ReportConfig
  ): string {
    const timestamp = new Date().toISOString();
    const mode = config?.runMode ?? 'offline_deterministic';
    const datasetVer = config?.datasetVersion ?? 'openpa-benchmark-v1.0';
    const strategy = config?.strategyName ?? 'Deterministic Rules (Tier 1)';

    let md = `# OpenPA Eval Benchmark Report\n\n`;
    md += `**Execution Timestamp:** \`${timestamp}\`  \n`;
    md += `**Dataset Version:** \`${datasetVer}\`  \n`;
    md += `**Evaluation Mode:** \`${mode}\`  \n`;
    md += `**Evaluator Configuration:** \`${strategy}\`  \n`;
    md += `**Total Evaluated Cases:** \`${metrics.totalCases}\`  \n\n`;

    md += `## 1. Executive Summary & KPIs\n\n`;
    md += `| Metric | Measured Result | CI Target Threshold |\n`;
    md += `| :--- | :--- | :--- |\n`;
    md += `| **Disposition Accuracy** | **${(metrics.dispositionAccuracy * 100).toFixed(1)}%** | $\\ge 95.0\\%$ |\n`;
    md += `| **Mean Requirement Accuracy** | **${(metrics.meanRequirementAccuracy * 100).toFixed(1)}%** | $\\ge 95.0\\%$ |\n`;
    md += `| **Balanced Requirement Accuracy** | **${(metrics.meanRequirementBalancedAccuracy * 100).toFixed(1)}%** | $\\ge 90.0\\%$ |\n`;
    md += `| **Macro Requirement F1** | **${(metrics.meanRequirementMacroF1 * 100).toFixed(1)}%** | $\\ge 90.0\\%$ |\n`;
    md += `| **Mean Grounding Precision** | **${(metrics.meanGroundingPrecision * 100).toFixed(1)}%** | $\\ge 95.0\\%$ |\n`;
    md += `| **Total Unsupported Citations** | **${metrics.totalUnsupportedCitations}** | **0 (Zero Tolerance)** |\n`;
    md += `| **Missing Evidence Recall** | **${(metrics.missingEvidenceRecall * 100).toFixed(1)}%** | $\\ge 85.0\\%$ |\n`;
    if (sensitivity) {
      md += `| **Counterfactual Sensitivity** | **${(sensitivity.counterfactualSensitivity * 100).toFixed(1)}%** | $\\ge 90.0\\%$ |\n`;
    }
    md += `| **Mean Cost Per Case** | **$${metrics.meanCostPerCase.toFixed(4)} USD** | $\\le \\$0.05$ |\n`;
    const costSafeStr = metrics.costPerSafeResolution != null
      ? `$${metrics.costPerSafeResolution.toFixed(4)} USD`
      : 'N/A (0 safe resolutions)';
    md += `| **Cost per Safe Resolution** | **${costSafeStr}** | $\\le \\$0.05$ |\n`;
    md += `| **Mean Latency per Case** | **${metrics.meanLatencyMs} ms** | $\\le 200\\text{ ms}$ |\n\n`;

    md += `## 2. Case-by-Case Breakdown\n\n`;
    md += `| Case ID | Expected | Predicted | Status | Req Acc | Grounding | Unsupported | Cost | Latency |\n`;
    md += `| :--- | :--- | :--- | :---: | :---: | :---: | :---: | :---: | :---: |\n`;
    for (const c of metrics.caseScores) {
      const matchBadge = c.dispositionMatch ? '✅ PASS' : '❌ FAIL';
      md += `| \`${c.caseId}\` | \`${c.expectedDisposition}\` | \`${c.predictedDisposition}\` | ${matchBadge} | ${(c.requirementAccuracy * 100).toFixed(0)}% | ${(c.groundingPrecision * 100).toFixed(0)}% | ${c.unsupportedCitations} | $${c.costUsd.toFixed(4)} | ${c.latencyMs}ms |\n`;
    }
    md += `\n`;

    if (sensitivity && sensitivity.results.length > 0) {
      md += `## 3. Counterfactual Sensitivity (Adversarial Robustness)\n\n`;
      md += `*Sensitivity evaluates whether perturbing a clinically determinative fact correctly flips a baseline compliant case into a non-compliant or escalated state.*\n\n`;
      md += `Summary: ${sensitivity.totalCorrectlyFlipped} / ${sensitivity.totalMutationsEvaluated} applicable vectors flipped (${(sensitivity.counterfactualSensitivity * 100).toFixed(1)}%). Inapplicable/no-op: ${sensitivity.totalSkippedInapplicable}, Baseline deficient: ${sensitivity.totalSkippedBaselineDeficient}.\n\n`;
      md += `| Case ID | Mutation Vector | Baseline | Mutated Result | Target Requirement | Vector Outcome |\n`;
      md += `| :--- | :--- | :--- | :--- | :--- | :---: |\n`;
      for (const m of sensitivity.results) {
        let badge = '❌ FAILED';
        if (m.status === 'passed') badge = '✅ PASS (FLIPPED)';
        else if (m.status === 'skipped_baseline_deficient') badge = '⚪ SKIPPED (baseline deficient)';
        else if (m.status === 'skipped_inapplicable_noop') badge = '⚪ SKIPPED (inapplicable/no-op)';
        md += `| \`${m.caseId}\` | \`${m.mutationType}\` | \`${m.baselineDisposition}\` | \`${m.mutatedDisposition}\` | \`${m.targetRequirementId || 'N/A'}\` | ${badge} |\n`;
      }
      md += `\n`;
    }

    md += `---\n*Generated by fhir-prior-auth-eval benchmark runner. Evaluates clinical evidence verification for prior authorization workflows.*\n`;
    return md;
  }
}
